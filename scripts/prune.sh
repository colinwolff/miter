#!/usr/bin/env bash
set -euo pipefail
echo "=== miter Workspace Disk Pruner ==="
if [ -d "target" ]; then
    echo "Before: $(du -sh target | cut -f1)"
fi
if [ -d "target/debug/deps" ]; then
    echo "deps entries before: $(ls target/debug/deps | wc -l | tr -d ' ')"
fi
rm -rf target/debug/incremental target/release/incremental
find target/debug/deps -name "*.dSYM" -exec rm -rf {} + 2>/dev/null || true
# The codegen objects of every unit ever built. `*.rcgu.o` is what rustc writes per codegen unit
# and does *not* delete after linking, so on this tree they had accumulated to 166 430 files —
# and a `target/debug/deps` directory of 171 918 entries makes *starting* any binary in it cost
# about a second of wall clock with no CPU spent (measured: 1.0–1.7 s at 171 918 entries, 0.04 s
# after this sweep at 5 488). That is the gate's real floor, because every runner starts a process
# per binary (cargo) or per test (nextest): the same nextest run went from 394.6 s to 62.2 s on
# the sweep alone, and `cargo test --workspace` from 143.6 s to 78.3 s.
#
# Deleting them is safe by construction: nothing *reads* an object file except the rustc
# invocation that just wrote it (they are intermediate artifacts of a link, not cargo inputs — a
# crate's fingerprint is its source and its dependencies, never its `.o`), so a removed object is
# either regenerated by a rebuild or was already inside the `.rlib` beside it. Verified both ways:
# an incremental rebuild after the sweep links, and the full gate passes.
find target -name "*.rcgu.o" -delete 2>/dev/null || true
rm -f /tmp/*xtest*.log /tmp/g_xtest*.log /tmp/ver_xtest*.log
find . -maxdepth 2 -name "*test*.redb*" -type f -delete 2>/dev/null || true
if [ -d "target/debug/deps" ]; then
    echo "deps entries after:  $(ls target/debug/deps | wc -l | tr -d ' ')"
fi
if [ -d "target" ]; then
    echo "After: $(du -sh target | cut -f1)"
fi
echo "Prune complete."
